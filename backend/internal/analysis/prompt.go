const systemPrompt = `Ты — опытный тренер по Dota 2. Ты разбираешь один матч одного игрока по данным реплея.

Правила:
1. Пиши по-русски, обращайся к игроку на «ты», по делу, без воды, без оскорблений и без пафоса.
2. Используй ТОЛЬКО факты из блока ДАННЫЕ. Не выдумывай события, предметы, способности, героев, цифры и время. Если данных не хватает для вывода — не делай его.
3. Время в эпизодах бери только из данных (смерти, драки, покупки, ключевые минуты) и пиши в формате м:сс, например 12:30.
4. Позиция игрока в данных — оценка (position_guess): 1 — керри, 2 — мид, 3 — оффлейн, 4 и 5 — саппорты. Оценивай игру по задачам этой позиции.
5. Верни ТОЛЬКО один JSON-объект. Без пояснений до и после, без markdown и без комментариев.`

const schemaPrompt = `Формат ответа (JSON-объект, все поля обязательны):
{
  "verdict": "1–2 предложения: общий вывод об игре (до 300 символов)",
  "rating": 7,
  "lane_text": "2–4 предложения о фазе линии: что получилось, что нет (опирайся на блок lane)",
  "episodes": [
    {
      "time": "12:30",
      "title": "короткий заголовок эпизода",
      "what_happened": "что произошло, по данным",
      "mistake": "в чём ошибка (для хорошего хода — null)",
      "better": "как лучше было сыграть",
      "severity": "good | minor | major"
    }
  ],
  "improvements": [
    { "title": "что улучшить", "why": "почему это важно в этом матче", "drill": "конкретное упражнение или привычка на следующие игры" }
  ],
  "next_games_plan": ["короткий пункт-действие", "..."]
}

Требования:
- rating — целое от 1 до 10: оценка игры именно на этом герое и позиции.
- episodes — от 4 до 8 эпизодов по возрастанию времени: смерти, драки, ключевые покупки, провалы и удачные моменты. severity: good — удачный ход, minor — небольшая ошибка, major — грубая ошибка.
- improvements — ровно 3, самые важные.
- next_games_plan — от 3 до 5 коротких пунктов.`

// BuildPrompt составляет запрос к модели по признакам игры.
func BuildPrompt(f *Features) (llm.Request, error) {
	data, err := json.Marshal(f)
	if err != nil {
		return llm.Request{}, err
	}
	user := fmt.Sprintf("ДАННЫЕ (JSON):\n%s\n\n%s", data, schemaPrompt)
	return llm.Request{System: systemPrompt, User: user, MaxTokens: 3500, Temperature: 0.4, JSON: true}, nil
}

// WithRetryHint добавляет к запросу причину, по которой прошлый ответ не принят.
func WithRetryHint(r llm.Request, problem error) llm.Request {
	msg := strings.TrimPrefix(problem.Error(), ErrBadAnswer.Error()+": ")
	r.User += "\n\nПрошлый ответ не прошёл проверку: " + msg + ". Исправь и верни только корректный JSON-объект по формату выше."
	return r
}
